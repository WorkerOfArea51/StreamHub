 * - [BroadcastPrimaryPurple]: Accent color representing global edge broadcasts (#A855F7)
 * - [BroadcastEmeraldAccent]: Vibrant green used for live status and "Content" drops (#00E676)
 * - [BroadcastSkyAccent]: Fresh cyan used for "Notice" updates and changelogs (#38BDF8)
 * - [BroadcastAmberAccent]: Warm amber used for warnings, maintenance, and alerts (#FFA726)
 * - [BroadcastRoseAccent]: Vivid red used for destructive actions like broadcast retirement (#FF5252)
 * =========================================================================================
 */

val BroadcastSurfaceDark = Color(0xFF14141E)
val BroadcastSurfaceCard = Color(0xFF181828)
val BroadcastSurfaceBorder = Color(0xFF262638)
val BroadcastPrimaryPurple = Color(0xFFA855F7)
val BroadcastEmeraldAccent = Color(0xFF00E676)
val BroadcastSkyAccent = Color(0xFF38BDF8)
val BroadcastAmberAccent = Color(0xFFFFA726)
